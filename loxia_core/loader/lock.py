"""`loxia.lock`: identidade e conteúdo das dependências (ADR-0104).

O lock é **gerado** por `loxia lock` e versionado junto do manifest. Ele fixa, para cada
dependência, a origem (`path` ou `git`+`rev`), a versão declarada (quando houver) e o
`sha256` da árvore de fontes. A representação é canônica — entradas ordenadas por nome,
chaves em ordem fixa, LF e nenhum caminho absoluto — para que dois manifests iguais
produzam bytes idênticos (I3).
"""

from __future__ import annotations

import tomllib
from dataclasses import dataclass, field
from pathlib import Path

LOCK_NAME = "loxia.lock"
LOCK_VERSION = 1
_HEADER = "# Generated by `loxia lock`; do not edit.\n"
_PACKAGE_KEYS = frozenset({"name", "path", "git", "rev", "commit", "version", "sha256"})
_TOP_LEVEL_KEYS = frozenset({"version", "package"})
_SHA256_LENGTH = 64


class LockError(Exception):
    """Lock inválido; a mensagem já está pronta para o diagnóstico."""

    def __init__(self, message: str, *, line: int = 1, column: int = 1) -> None:
        super().__init__(message)
        self.message = message
        self.line = line
        self.column = column


@dataclass(frozen=True)
class LockedPackage:
    """Uma dependência travada: origem, identidade e hash do conteúdo."""

    name: str
    sha256: str
    path: str | None = None
    git: str | None = None
    rev: str | None = None
    commit: str | None = None
    version: str | None = None


@dataclass(frozen=True)
class Lock:
    packages: dict[str, LockedPackage] = field(default_factory=dict)
    version: int = LOCK_VERSION


def parse_lock(path: Path, text: str) -> Lock:
    """Valida o lock inteiro; qualquer divergência é `LockError` (I3: sem inferência)."""
    try:
        raw: object = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise LockError(
            f"Invalid TOML: {error}.",
            line=getattr(error, "lineno", 1) or 1,
            column=getattr(error, "colno", 1) or 1,
        ) from None

    data = _table(raw, "lock")
    unknown = sorted(set(data) - _TOP_LEVEL_KEYS)
    if unknown:
        raise LockError("Unknown lock key(s): " + ", ".join(unknown) + ".")
    version = data.get("version")
    if version != LOCK_VERSION:
        raise LockError(f"Unsupported lock version: expected {LOCK_VERSION}.")
    entries = data.get("package", [])
    if not isinstance(entries, list):
        raise LockError("Expected 'package' to be an array of tables.")

    packages: dict[str, LockedPackage] = {}
    for entry in entries:
        package = _package(entry)
        if package.name in packages:
            raise LockError(f"Duplicate package '{package.name}' in the lock.")
        packages[package.name] = package
    return Lock(packages, LOCK_VERSION)


def render_lock(lock: Lock) -> str:
    """Representação canônica: mesma árvore ⇒ mesmos bytes (teste de determinismo)."""
    lines = [_HEADER, f"version = {lock.version}\n"]
    for name in sorted(lock.packages):
        package = lock.packages[name]
        lines.append("\n[[package]]\n")
        lines.append(f"name = {_quote(package.name)}\n")
        if package.path is not None:
            lines.append(f"path = {_quote(package.path)}\n")
        if package.git is not None:
            lines.append(f"git = {_quote(package.git)}\n")
        if package.rev is not None:
            lines.append(f"rev = {_quote(package.rev)}\n")
        if package.commit is not None:
            lines.append(f"commit = {_quote(package.commit)}\n")
        if package.version is not None:
            lines.append(f"version = {_quote(package.version)}\n")
        lines.append(f"sha256 = {_quote(package.sha256)}\n")
    return "".join(lines)


def read_lock(path: Path) -> Lock | None:
    """Lê o lock se existir; ausência não é erro (`--frozen` decide)."""
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None
    except OSError:
        raise LockError("Can't read loxia.lock.") from None
    return parse_lock(path, text)


def write_lock(path: Path, lock: Lock) -> None:
    path.write_text(render_lock(lock), encoding="utf-8", newline="\n")


def _table(value: object, what: str) -> dict[str, object]:
    if not isinstance(value, dict):
        raise LockError(f"Expected '{what}' to be a table.")
    return {str(key): item for key, item in value.items()}


def _string(value: object, what: str) -> str:
    if not isinstance(value, str) or not value:
        raise LockError(f"Expected '{what}' to be a non-empty string.")
    return value


def _package(entry: object) -> LockedPackage:
    table = _table(entry, "package")
    unknown = sorted(set(table) - _PACKAGE_KEYS)
    if unknown:
        raise LockError("Unknown package key(s): " + ", ".join(unknown) + ".")
    name = _string(table.get("name"), "package.name")
    sha256 = _string(table.get("sha256"), f"package.{name}.sha256")
    if len(sha256) != _SHA256_LENGTH or any(ch not in "0123456789abcdef" for ch in sha256):
        raise LockError(f"Invalid sha256 for package '{name}'.")
    path = table.get("path")
    git = table.get("git")
    if (path is None) == (git is None):
        raise LockError(f"Package '{name}' needs exactly one of 'path' or 'git'.")
    if path is not None:
        raw_path = _string(path, f"package.{name}.path")
        if Path(raw_path).is_absolute():
            raise LockError(f"Package '{name}' path must be relative to the manifest.")
        path = raw_path
    if git is not None:
        git = _string(git, f"package.{name}.git")
        if table.get("rev") is None or table.get("commit") is None:
            raise LockError(f"Git package '{name}' needs 'rev' and 'commit'.")
    return LockedPackage(
        name=name,
        sha256=sha256,
        path=path if isinstance(path, str) else None,
        git=git if isinstance(git, str) else None,
        rev=_optional(table.get("rev"), f"package.{name}.rev"),
        commit=_optional(table.get("commit"), f"package.{name}.commit"),
        version=_optional(table.get("version"), f"package.{name}.version"),
    )


def _optional(value: object, what: str) -> str | None:
    if value is None:
        return None
    return _string(value, what)


def _quote(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'
