"""Generates `runtime/kernel_gen.h` from the single primitive table (ADR-0071).

The generated header declares each primitive's C symbol with the signature the
lowering expects (`params`/`result`/`site`). `kernel.c` includes it, so a mismatch
between the table and the C definition fails at compile time instead of in tests.

Usage: `python runtime/gen_kernel.py --write` (or `--check`, which only compares).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from loxia_core.execution.primitives import PRIMITIVES, Primitive  # noqa: E402
from loxia_core.frontend.ty import (  # noqa: E402
    BOOL,
    BYTES,
    FLOAT,
    INT,
    NIL,
    STRING,
    ListTy,
    TupleTy,
    Ty,
    UnionTy,
)

OUT = ROOT / "runtime" / "kernel_gen.h"


def _c_type(ty: Ty, *, result: bool) -> str:
    if ty is STRING or ty is BYTES or isinstance(ty, (ListTy, TupleTy)):
        return "void *" if result else "const void *"
    if isinstance(ty, UnionTy):
        return "void *"
    if ty is INT:
        return "int64_t"
    if ty is BOOL:
        return "int32_t"
    if ty is FLOAT:
        return "double"
    if ty is NIL:
        return "void"
    raise SystemExit(f"type without a C mapping: {ty!r}")


def _signature(primitive: Primitive) -> str:
    result = _c_type(primitive.result, result=True)
    params = [_c_type(param, result=False) for param in primitive.params]
    if primitive.site:
        params.extend(["int32_t", "int32_t"])
    joined = ", ".join(params) if params else "void"
    return f"{result} {primitive.c_symbol}({joined});"


def render() -> str:
    lines = [
        "/*",
        " * Generated by `runtime/gen_kernel.py` from",
        " * `loxia_core/execution/primitives.py`. DO NOT EDIT BY HAND.",
        " *",
        " * Each declaration is the signature used by the lowering; `kernel.c` includes",
        " * this header, so the table and the C definition cannot diverge without",
        " * breaking the build (ADR-0071, ADR-0094).",
        " */",
        "#ifndef LOX_KERNEL_GEN_H",
        "#define LOX_KERNEL_GEN_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    for primitive in PRIMITIVES:
        lines.append(f"/* {primitive.lox} */")
        lines.append(_signature(primitive))
    lines.extend(["", "#endif /* LOX_KERNEL_GEN_H */", ""])
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"{OUT.relative_to(ROOT)}: {len(PRIMITIVES)} primitives")
        return 0
    if "--check" in argv:
        if current != text:
            print(f"out of date: {OUT.relative_to(ROOT)}")
            print("Run: make primitives")
            return 1
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
